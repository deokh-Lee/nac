package com.saltlux.nac.subject;

public class SubjectPolicyCandidate {
    private String itemCd;
    private String subClsNm;
    private String topicNm;
    private String prevGovNm;
    private String ternStart;
    private String ternEnd;
    private String description;

    public String getItemCd() { return itemCd; }
    public void setItemCd(String itemCd) { this.itemCd = itemCd; }
    public String getSubClsNm() { return subClsNm; }
    public void setSubClsNm(String subClsNm) { this.subClsNm = subClsNm; }
    public String getTopicNm() { return topicNm; }
    public void setTopicNm(String topicNm) { this.topicNm = topicNm; }
    public String getPrevGovNm() { return prevGovNm; }
    public void setPrevGovNm(String prevGovNm) { this.prevGovNm = prevGovNm; }
    public String getTernStart() { return ternStart; }
    public void setTernStart(String ternStart) { this.ternStart = ternStart; }
    public String getTernEnd() { return ternEnd; }
    public void setTernEnd(String ternEnd) { this.ternEnd = ternEnd; }
    public String getDescription() { return description; }
    public void setDescription(String description) { this.description = description; }
}
